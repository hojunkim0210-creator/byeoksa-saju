  /** year년 idx번째 절기(0=소한 … 11=대설)의 UTC 밀리초. 범위 밖이면 null */
  function getTermUtcMs(year, idx) {
    if (year < TERM_BASE_YEAR || year > TERM_LAST_YEAR || idx < 0 || idx > 11) return null;
    return SOLAR_TERMS_MIN[(year - TERM_BASE_YEAR) * 12 + idx] * 60000;
  }

  let _seoulFmt = null;
  /**
   * 해당 순간의 서울 표준시 오프셋(분). 브라우저의 IANA 'Asia/Seoul' 역사 데이터를 사용하므로
   * 1954~1961년 UTC+8:30, 1948~1960년·1987~1988년 서머타임이 자동 반영된다.
   */
  function seoulOffsetMinutes(utcMs) {
    try {
      if (!_seoulFmt) {
        _seoulFmt = new Intl.DateTimeFormat('en-US', { timeZone: 'Asia/Seoul', hourCycle: 'h23',
          year: 'numeric', month: 'numeric', day: 'numeric', hour: 'numeric', minute: 'numeric' });
      }
      const p = {};
      _seoulFmt.formatToParts(new Date(utcMs)).forEach(x => { p[x.type] = x.value; });
      const asUtc = Date.UTC(+p.year, +p.month - 1, +p.day, +p.hour % 24, +p.minute);
      return Math.round((asUtc - Math.floor(utcMs / 60000) * 60000) / 60000);
    } catch (e) {
      return 540; // Intl 미지원 환경: 현행 KST(UTC+9)
    }
  }

  /** 서울 현지 시각(벽시계) → UTC 밀리초 */
  function seoulLocalToUtc(y, m, d, hh, mm) {
    const local = Date.UTC(y, m - 1, d, hh, mm);
    let utc = local - 540 * 60000;
    for (let k = 0; k < 3; k++) utc = local - seoulOffsetMinutes(utc) * 60000;
    return utc;
  }

  /** UTC 밀리초 → 'M월 D일 HH:MM' (서울 현지 시각) */
  function formatSeoul(utcMs) {
    const t = new Date(utcMs + seoulOffsetMinutes(utcMs) * 60000);
    const pad = n => String(n).padStart(2, '0');
    return `${t.getUTCMonth() + 1}월 ${t.getUTCDate()}일 ${pad(t.getUTCHours())}:${pad(t.getUTCMinutes())}`;
  }

  /**
   * 출생 시간 구간(UTC). 시진을 고르면 그 2시간(자시는 전날 23:30부터), 모르면 그날 하루 전체.
   * 대표 시각(rep)은 구간의 한가운데 — 시진만 알 때 가장 오차가 작은 추정이다.
   */
  function getBirthWindow(y, m, d, hourVal) {
    const dayStart = seoulLocalToUtc(y, m, d, 0, 0);
    let start, end;
    if (hourVal !== null && hourVal !== undefined && hourVal >= 0 && hourVal <= 11) {
      start = dayStart + (hourVal * 120 - 30) * 60000;
      end = start + 120 * 60000;
    } else {
      start = dayStart;
      end = seoulLocalToUtc(y, m, d, 23, 59) + 60000;
    }
    return { start, end, rep: Math.floor((start + end) / 2) };
  }

