def _series(terms, tau):
    return sum(a * math.cos(b + c * tau) for a, b, c in terms)

def sun_apparent_lon(jd_tt):
    """태양 겉보기 황경(도). VSOP87 + FK5 보정 + 장동(주요항) + 광행차."""
    tau = (jd_tt - 2451545.0) / 365250
    L = sum(_series(t, tau) * tau ** i for i, t in enumerate((L0, L1, L2, L3, L4, L5))) / 1e8
    lon = math.degrees(L) + 180.0                       # 지구 일심 → 태양 지심
    T = tau * 10
    lon += -0.09033 / 3600                               # VSOP → FK5
    om = math.radians(125.04452 - 1934.136261 * T)
    Ls = math.radians(280.4665 + 36000.7698 * T)
    Lm = math.radians(218.3165 + 481267.8813 * T)
    dpsi = (-17.20 * math.sin(om) - 1.32 * math.sin(2 * Ls) - 0.23 * math.sin(2 * Lm) + 0.21 * math.sin(2 * om)) / 3600
    aberr = -20.4898 / 3600                              # R≈1 AU 근사 (오차 < 0.4")
    return (lon + dpsi + aberr) % 360

def term_instant_utc(year, idx):
    """year년 idx번째 절기의 순간(UTC datetime)."""
    target = TERMS[idx][1]
    month = idx + 1
    lo = datetime(year, month, 1, tzinfo=timezone.utc) - timedelta(days=3)
    hi = datetime(year, month, 15, tzinfo=timezone.utc)
    def f(dt):  # dt는 UT로 취급 → TT로 변환해 황경 계산
        jd_ut = dt.timestamp() / 86400 + 2440587.5
        jd_tt = jd_ut + delta_t(year) / 86400
        d = sun_apparent_lon(jd_tt) - target
        return (d + 180) % 360 - 180
    for _ in range(60):
        mid = lo + (hi - lo) / 2
        if f(mid) < 0: lo = mid
        else: hi = mid
    return lo + (hi - lo) / 2

def build(y0=1900, y1=2100):
    """{year: [12개 절기의 UTC epoch 분]} — JS에서 Date.UTC 분 단위로 사용."""
    out = {}
    for y in range(y0, y1 + 1):
        out[y] = [round(term_instant_utc(y, i).timestamp() / 60) for i in range(12)]
    return out

