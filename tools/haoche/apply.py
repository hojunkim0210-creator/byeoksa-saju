def run():
    sc = scope.in_scope()
    diff = []
    for rel, idxs in sc.items():
        lines = scope.read(rel)
        changed = False
        for i in sorted(idxs):
            if i >= len(lines): continue
            line = lines[i]
            if scope.skip_line(rel, line): continue
            body, tail = scope.strip_comment(line)
            spans = other_quote_spans(body) + protected_spans(body)
            nb = convert_endings(body, spans)
            nb = convert_pronouns(nb, other_quote_spans(nb) + protected_spans(nb))
            if nb != body:
                diff.append(f'{rel}:{i + 1}\n- {body.strip()}\n+ {nb.strip()}\n')
                lines[i] = nb + tail; changed = True
        text = '\n'.join(lines)
        for old, new in DIRECT.get(rel, []):
            if old in text:
                text = text.replace(old, new); changed = True; diff.append(f'{rel}: (문장째)\n- {old}\n+ {new}\n')
            else:
                diff.append(f'{rel}: !! 못 찾음: {old[:40]}\n')
        if changed and MODE == 'write':
            open(os.path.join(REPO, rel), 'w', encoding='utf-8').write(text)
    open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'diff.txt'), 'w', encoding='utf-8').write('\n'.join(diff))
    print(f'바뀌는 줄 {len([d for d in diff if d.startswith("site")])}개 ({MODE})')


run()
