QUOTATIVE = re.compile(r'^(?:[?!.…]*)(?:</?(?:em|strong)>)*\s?(라며|라고|라는|라던|라니|라면서|이라|하며|하고|하는|하던|하다|한다|한|했|하면|하더|하니|면서|며|고|는|를|로|란|은|을|이|가|에|와|만|도|처럼|같은)')
QUOTES = {'"': '"', "'": "'", '“': '”', '‘': '’'}


def other_quote_spans(body):
    """바꾸지 않을 따옴표 구간들 [(시작, 끝)].
    - JS 문자열을 감싸는 따옴표(앞이 : ( [ { , = + ? 이고 뒤가 , ) ] } ; : + 또는 줄 끝)는 벽사견 말이라 바꾼다
    - 글 속 따옴표는 안쪽이 . ! ? … 로 끝나는 벽사견 말이고 뒤에 인용 조사가 안 붙을 때만 바꾸고,
      나머지(다른 사람 말·손님 속말·주문·꼬리표)는 그대로 둔다"""
    spans = []
    # HTML 꾸밈 표시(class="…", style="…" 등) 속 따옴표는 대사 따옴표가 아니다 — 같은 길이로 가려 두고 짝짓는다
    masked = re.sub(r'=(["\'])[^"\'<>]*\1', lambda m: '=' + '§' * (len(m.group(0)) - 1), body)
    for op, cl in QUOTES.items():
        i = 0
        while True:
            a = masked.find(op, i)
            if a == -1: break
            b = masked.find(cl, a + 1)
            if b == -1: break
            content = body[a + 1:b]
            before = masked[:a].rstrip(); after = body[b + 1:]
            js_delim = (before == '' or before[-1] in '[(:{,=+?') and (after.strip() == '' or after.lstrip()[:1] in ',)]};:+')
            if not js_delim and re.search(r'[가-힣]', content):
                speech = re.search(r'[.!?…]\s*(?:</?(?:em|strong|span)[^>]*>)*\s*$', content) and not QUOTATIVE.match(after)
                if not speech: spans.append((a, b))
            i = b + 1
    return spans


def protected_spans(body):
    out = []
    for p in PROTECT:
        k = body.find(p)
        while k != -1:
            out.append((k, k + len(p))); k = body.find(p, k + 1)
    return out


def inside(pos, spans):
    return any(a <= pos <= b for a, b in spans)


TAG_END = re.compile(r'(</(?:strong|em|span|b)>)(이다|다)(?=…|\.\.\.|[.!?"\'`<]|\s*$)')   # '…(육합)</strong>다.' 처럼 굵은 글씨 바로 뒤의 말끝 (42에서 더함)


def convert_endings(body, spans):
    res, last = [], 0
    for m in TAG_END.finditer(body):
        if inside(m.start(), spans): continue
        res.append(body[last:m.start()]); res.append(m.group(1) + ('이오' if m.group(2) == '이다' else '요')); last = m.end()
    res.append(body[last:]); body = ''.join(res)
    out, last = [], 0
    for m in scope.TOKEN.finditer(body):
        w = m.group(1)
        if not scope.candidates(w) or inside(m.start(), spans): continue
        new = MANUAL[w] if w in MANUAL else propose(w)
        if not new or new == w: continue
        out.append(body[last:m.start()]); out.append(new); last = m.end()
    out.append(body[last:])
    return ''.join(out)


