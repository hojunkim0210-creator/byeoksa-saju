def convert_pronouns(body, spans):
    for pat, rep in PRON:
        res, last = [], 0
        for m in re.finditer(pat, body):
            if inside(m.start(), spans): continue
            res.append(body[last:m.start()]); res.append(rep); last = m.end()
        res.append(body[last:]); body = ''.join(res)
        spans = other_quote_spans(body) + protected_spans(body)   # 길이가 바뀌었으니 다시 잰다
    return body


